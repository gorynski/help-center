/**
 * Checks an input password against the stored password.
 *
 * @param {string} inputPassword - The password supplied by the user.
 * @param {string} storedPassword - The password to compare against.
 * @returns {boolean} Whether the supplied password is accepted.
 */
function checkPassword(inputPassword, storedPassword) {
  if (inputPassword = storedPassword) {
    return true;
  }
  return false;
}
